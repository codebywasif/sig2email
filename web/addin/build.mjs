// Builds the add-in into dist/: two self-contained bundles, the HTML hosts and the manifest template.
// Nothing is configured here. The Sig2Email API serves dist/ under /addin/ and fills in its public address and the
// Entra application id from the portal's System settings when a file is requested.
import { build } from 'esbuild';
import { copyFileSync, mkdirSync, rmSync } from 'node:fs';

mkdirSync('dist', { recursive: true });
rmSync('dist/manifest.xml', { force: true }); // from older builds; the manifest is now generated by the API
await build({
  entryPoints: { launchevent: 'src/launchevent.ts', taskpane: 'src/taskpane.ts' },
  bundle: true,
  format: 'iife',          // classic Outlook on Windows loads launchevent.js into a script-only runtime
  target: 'es2019',
  minify: true,
  outdir: 'dist',
});
copyFileSync('src/manifest.xml', 'dist/manifest.template.xml');
for (const file of ['launchevent.html', 'taskpane.html']) copyFileSync(`src/${file}`, `dist/${file}`);
console.log('Add-in built. Start the API and download the manifest from the portal: System > Outlook add-in.');
